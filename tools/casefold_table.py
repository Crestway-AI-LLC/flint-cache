"""Generate crates/flint-vec/src/casefold/table.rs from Unicode's CaseFolding.txt.

Why this exists: a SORTABLE TEXT or TAG field sorts by its value case-folded,
as RediSearch folds it with ICU's full case folding (ADR-0063 amendment 1).
That folding is CaseFolding.txt's C and F mappings, so the table is generated
from the file, not written by hand. The file is vendored beside the table, and
a unit test there checks every one of its lines against `fold`, so a table
that drifts from the file fails the build's tests.

The input is a downloaded file: it is parsed strictly, and anything that is
not a well-formed line of the expected version stops the script.

Usage:
    python3 -I tools/casefold_table.py <CaseFolding.txt> \\
        > crates/flint-vec/src/casefold/table.rs
"""

import re
import sys

VERSION = "17.0.0"
LINE = re.compile(r"^([0-9A-F]{4,6}); ([CFST]); ([0-9A-F]{4,6}(?: [0-9A-F]{4,6})*); # .*$")


def scalar(hexdigits, where):
    cp = int(hexdigits, 16)
    if cp > 0x10FFFF or 0xD800 <= cp <= 0xDFFF:
        sys.exit(f"{where}: {hexdigits} is not a Unicode scalar value")
    return cp


def main(path):
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")
    if lines[0] != f"# CaseFolding-{VERSION}.txt":
        sys.exit(f"{path}: the first line is {lines[0]!r}, not version {VERSION}'s")
    folds = {}
    for n, line in enumerate(lines, 1):
        if not line or line.startswith("#"):
            continue
        m = LINE.match(line)
        if not m:
            sys.exit(f"{path}:{n}: not a CaseFolding line: {line!r}")
        code, status, mapping = m.groups()
        if status not in "CF":
            continue
        cp = scalar(code, f"{path}:{n}")
        if cp in folds:
            sys.exit(f"{path}:{n}: a second C or F mapping for {code}")
        folds[cp] = [scalar(h, f"{path}:{n}") for h in mapping.split(" ")]
    out = sys.stdout
    out.write("// SPDX-License-Identifier: Unicode-3.0\n")
    out.write(f"// Generated by tools/casefold_table.py from Unicode {VERSION}'s\n")
    out.write("// CaseFolding.txt, vendored beside this file: its C and F mappings,\n")
    out.write("// by code point. Licence and copyright in COPYING beside this file.\n")
    out.write("// Do not edit; generate it again.\n\n")
    out.write(f"/// Each character's full case folding, Unicode {VERSION}, ordered by\n")
    out.write("/// character. A character not here folds to itself.\n")
    out.write("pub(super) static FOLDS: &[(char, &str)] = &[\n")
    for cp in sorted(folds):
        to = "".join(f"\\u{{{c:x}}}" for c in folds[cp])
        out.write(f"    ('\\u{{{cp:x}}}', \"{to}\"),\n")
    out.write("];\n")
    print(f"{len(folds)} mappings", file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
